<?php if ($done): ?>
  <h1>Installation complete</h1>
  <p>For safety, delete the <strong>install</strong> folder from your server with your FTP client. It stays locked either way.</p>
  <a class="btn" href="../">Open Static Site Maker</a>
<?php elseif ($step === 'locked'): ?>
  <h1>Already installed</h1>
  <p>This platform is installed, so the installer is locked. To start over, delete <strong>config/config.php</strong>.</p>
  <a class="btn" href="../">Open Static Site Maker</a>
<?php else: ?>
  <h1>Install Static Site Maker</h1>
  <ol class="steps">
    <?php foreach ($stepNames as $key => $label): ?>
      <li class="<?= $key === $step ? 'on' : '' ?>"><?= e($label) ?></li>
    <?php endforeach; ?>
  </ol>
  <?php if ($error): ?><div class="err" role="alert"><?= e($error) ?></div><?php endif; ?>

  <?php if ($step === 'requirements'): ?>
    <ul class="checks">
      <?php foreach ($checks as [$label, $ok]): ?>
        <li><span><?= e($label) ?></span><span class="<?= $ok ? 'ok' : 'no' ?>"><?= $ok ? 'OK' : 'Missing' ?></span></li>
      <?php endforeach; ?>
    </ul>
    <?php if ($allOk): ?>
      <a class="btn" href="?step=database">Continue</a>
    <?php else: ?>
      <p>Fix the items above in your hosting control panel, then reload this page.</p>
    <?php endif; ?>

  <?php elseif ($step === 'database'): ?>
    <form method="post" action="?step=database">
      <input type="hidden" name="csrf" value="<?= e($_SESSION['csrf']) ?>">
      <div class="row">
        <label>Database host <input name="host" required value="<?= e($db['host']) ?>"></label>
        <label>Port <input name="port" value="<?= e($db['port']) ?>"></label>
      </div>
      <label>Database name <input name="name" required value="<?= e($db['name']) ?>"></label>
      <label>Username <input name="user" required autocomplete="off" value="<?= e($db['user']) ?>"></label>
      <label>Password <input name="pass" type="password" autocomplete="off" value="<?= e($db['pass']) ?>"></label>
