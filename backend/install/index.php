      <label>Platform name <input name="site_name" value="<?= e($site['site_name']) ?>"></label>
      <label>Your name <input name="admin_name" required value="<?= e($site['admin_name']) ?>"></label>
      <label>Email <input name="admin_email" type="email" required value="<?= e($site['admin_email']) ?>"></label>
      <label>Password (at least 8 characters) <input name="admin_password" type="password" minlength="8" required></label>
      <label class="check"><input type="checkbox" name="allow_registration" <?= $site['allow_registration'] ? 'checked' : '' ?>> Let visitors create their own accounts</label>
      <button>Install</button>
    </form>
  <?php endif; ?>
<?php endif; ?>
