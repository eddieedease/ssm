         background: #f4f4f5; color: var(--ink); font: 15px/1.5 system-ui, sans-serif; }
  main { width: 100%; max-width: 460px; background: #fff; border: 1px solid var(--line); border-radius: 12px; padding: 28px; }
  h1 { font-size: 20px; margin: 0 0 4px; }
