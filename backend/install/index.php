<?php
declare(strict_types=1);

require dirname(__DIR__) . '/src/bootstrap.php';

session_name('ssm_install');
session_start();
$_SESSION['csrf'] ??= bin2hex(random_bytes(16));

const MIN_PHP = '8.1.0';

function e(mixed $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES);
}

function requirements(): array
{
    $writable = static fn(string $dir) => is_dir($dir) && is_writable($dir);
    return [
        ['PHP ' . MIN_PHP . ' or newer (found ' . PHP_VERSION . ')', version_compare(PHP_VERSION, MIN_PHP, '>=')],
        ['PDO MySQL extension', extension_loaded('pdo_mysql')],
        ['Zip extension (for site exports)', class_exists(ZipArchive::class)],
        ['Fileinfo extension (for upload checks)', extension_loaded('fileinfo')],
        ['config/ folder is writable', $writable(SSM_ROOT . '/config')],
        ['uploads/ folder is writable', $writable(SSM_UPLOADS)],
    ];
}

function connectFrom(array $db): PDO
{
    return Db::connect($db['host'], (int) $db['port'], $db['name'], $db['user'], $db['pass']);
}

function install(array $db, array $site): void
{
    $pdo = connectFrom($db);
    $schema = str_replace('{prefix}', $db['prefix'], (string) file_get_contents(__DIR__ . '/schema.sql'));
    foreach (array_filter(array_map('trim', explode(';', $schema))) as $statement) {
        $pdo->exec($statement);
    }

    $pdo->prepare("INSERT INTO {$db['prefix']}users (name, email, password_hash, is_admin) VALUES (?, ?, ?, 1)")
        ->execute([$site['admin_name'], $site['admin_email'], password_hash($site['admin_password'], PASSWORD_DEFAULT)]);

    $config = [
        'site_name' => $site['site_name'],
        'allow_registration' => $site['allow_registration'],
        'db_host' => $db['host'],
        'db_port' => (int) $db['port'],
        'db_name' => $db['name'],
        'db_user' => $db['user'],
        'db_pass' => $db['pass'],
        'db_prefix' => $db['prefix'],
    ];
    $php = "<?php\n// Generated by the installer.\nreturn " . var_export($config, true) . ";\n";
    if (file_put_contents(SSM_CONFIG_FILE, $php, LOCK_EX) === false) {
        throw new RuntimeException('Could not write config/config.php.');
    }
    chmod(SSM_CONFIG_FILE, 0640);
}

$installed = is_file(SSM_CONFIG_FILE);
$done = isset($_GET['done']) && !empty($_SESSION['finished']);
$step = $installed ? 'locked' : (string) ($_GET['step'] ?? 'requirements');
$error = null;
$db = $_SESSION['db'] ?? [
    'host' => getenv('SSM_DEV_DB_HOST') ?: 'localhost',
    'port' => '3306',
    'name' => getenv('SSM_DEV_DB_NAME') ?: '',
    'user' => getenv('SSM_DEV_DB_USER') ?: '',
    'pass' => getenv('SSM_DEV_DB_PASS') ?: '',
    'prefix' => 'ssm_',
];
$site = ['site_name' => 'Static Site Maker', 'admin_name' => '', 'admin_email' => '', 'allow_registration' => false];

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!hash_equals($_SESSION['csrf'], (string) ($_POST['csrf'] ?? ''))) {
        $error = 'Your session expired. Please try again.';
    } elseif ($step === 'database') {
        $db = [
            'host' => trim((string) $_POST['host']),
            'port' => trim((string) $_POST['port']) ?: '3306',
            'name' => trim((string) $_POST['name']),
            'user' => trim((string) $_POST['user']),
            'pass' => (string) $_POST['pass'],
            'prefix' => trim((string) $_POST['prefix']),
        ];
        if (!preg_match('/^[A-Za-z0-9_]{0,20}$/', $db['prefix'])) {
            $error = 'The table prefix may only contain letters, digits and underscores.';
        } else {
            try {
                $pdo = connectFrom($db);
                $taken = $pdo->prepare('SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = ? AND table_name = ?');
                $taken->execute([$db['name'], $db['prefix'] . 'users']);
                if ((int) $taken->fetchColumn() > 0) {
                    $error = 'This database already holds an installation with that table prefix. Choose another prefix.';
                } else {
                    $_SESSION['db'] = $db;
                    header('Location: ?step=site');
                    exit;
                }
            } catch (PDOException $ex) {
                $error = 'Could not connect: ' . $ex->getMessage();
            }
        }
    } elseif ($step === 'site' && isset($_SESSION['db'])) {
        $site = [
            'site_name' => trim((string) $_POST['site_name']) ?: 'Static Site Maker',
            'admin_name' => trim((string) $_POST['admin_name']),
            'admin_email' => strtolower(trim((string) $_POST['admin_email'])),
            'admin_password' => (string) $_POST['admin_password'],
            'allow_registration' => isset($_POST['allow_registration']),
        ];
        if ($site['admin_name'] === '' || !filter_var($site['admin_email'], FILTER_VALIDATE_EMAIL)) {
            $error = 'Enter the administrator\'s name and a valid email address.';
        } elseif (strlen($site['admin_password']) < 8) {
            $error = 'The password must be at least 8 characters.';
        } else {
            try {
                install($_SESSION['db'], $site);
                unset($_SESSION['db']);
                $_SESSION['finished'] = true;
                header('Location: ?done=1');
                exit;
            } catch (Throwable $ex) {
                $error = 'Installation failed: ' . $ex->getMessage();
            }
        }
    }
}

if ($step === 'site' && !isset($_SESSION['db']) && !$installed) {
    $step = 'database';
}
$checks = requirements();
$allOk = !in_array(false, array_column($checks, 1), true);
$stepNames = ['requirements' => 'Requirements', 'database' => 'Database', 'site' => 'Administrator'];
?>
