  button, a.btn { display: inline-block; border: 0; border-radius: 7px; background: var(--accent); color: #fff;
         padding: 9px 16px; font: inherit; font-weight: 600; text-decoration: none; cursor: pointer; }
  .err { background: #fef2f2; color: #b91c1c; border-radius: 7px; padding: 9px 12px; margin-bottom: 14px; font-size: 14px; overflow-wrap: anywhere; }
  ul.checks { list-style: none; padding: 0; margin: 0 0 18px; }
  ul.checks li { padding: 6px 0; border-bottom: 1px solid var(--line); display: flex; justify-content: space-between; gap: 12px; }
  .ok { color: #15803d; font-weight: 600; } .no { color: #b91c1c; font-weight: 600; }
</style>
